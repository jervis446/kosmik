/**
 * Deploy fallback for networks that break Workers static-asset uploads (for example an HTTP
 * proxy that rewrites the Authorization header, which the asset upload uses for its own
 * short-lived token). Normally deploy with `npx wrangler deploy`, which uploads app/dist as
 * static assets.
 *
 * This script puts the web app inside the Worker instead: it copies the files the app actually
 * uses from app/dist into api/.web-embed/, writes an entry point that serves them before
 * handing everything else to src/index.ts, and writes api/wrangler.embedded.json (the same
 * config as wrangler.jsonc, minus "assets"). Then:
 *
 *   node scripts/embed-web.ts && npx wrangler deploy -c wrangler.embedded.json
 *
 * Only files referenced from index.html or the JavaScript bundle are included, so unused font
 * weights and icons are left out. Both outputs are git-ignored.
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative } from 'node:path';

const API = new URL('../', import.meta.url).pathname;
const DIST = join(API, '../app/dist');
const OUT = join(API, '.web-embed');

const TYPES: Record<string, string> = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.svg': 'image/svg+xml',
  '.ttf': 'font/ttf',
  '.woff2': 'font/woff2',
};

/** Removes // and /* *\/ comments from JSONC, leaving string contents alone. */
export function stripJsonComments(src: string): string {
  let out = '';
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (c === '"') {
      const start = i;
      for (i++; i < src.length && src[i] !== '"'; i++) if (src[i] === '\\') i++;
      out += src.slice(start, i + 1);
    } else if (c === '/' && src[i + 1] === '/') {
      while (i < src.length && src[i] !== '\n') i++;
      out += '\n';
    } else if (c === '/' && src[i + 1] === '*') {
      i = src.indexOf('*/', i + 2) + 1;
    } else out += c;
  }
  return out.replace(/,(\s*[}\]])/g, '$1');
}

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

function main() {
  if (!existsSync(join(DIST, 'index.html'))) throw new Error('Build the app first: cd app && npm run build:web');
  const files = walk(DIST).map((p) => '/' + relative(DIST, p).split('\\').join('/'));
  const text = files
    .filter((f) => f === '/index.html' || f.endsWith('.js'))
    .map((f) => readFileSync(join(DIST, f), 'utf8'))
    .join('\n');
  // Keep the pages and scripts, plus any other file whose name the app refers to.
  const used = files.filter((f) => TYPES[extname(f)] && (f.endsWith('.html') || f.endsWith('.js') || text.includes(f.slice(f.lastIndexOf('/') + 1))));

  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT);
  const imports: string[] = [];
  const entries: string[] = [];
  used.forEach((f, i) => {
    copyFileSync(join(DIST, f), join(OUT, `${i}.bin`));
    imports.push(`import f${i} from './${i}.bin';`);
    entries.push(`  ${JSON.stringify(f)}: [f${i}, ${JSON.stringify(TYPES[extname(f)])}],`);
  });

  writeFileSync(
    join(OUT, 'entry.ts'),
    `// Generated by scripts/embed-web.ts. Do not edit.
import worker from '../src/index.ts';
${imports.join('\n')}

const FILES: Record<string, [ArrayBuffer, string]> = {
${entries.join('\n')}
};

function serve(req: Request, path: string): Response | null {
  const file = FILES[path];
  // Single-page app: routes without a file extension get index.html.
  const hit = file ?? (/\\.[a-z0-9]+$/i.test(path) ? undefined : FILES['/index.html']);
  if (!hit) return null;
  // Hashed bundles and fonts never change; pages must be revalidated.
  const immutable = /[.-][0-9a-f]{16,}\\./.test(path) && path !== '/index.html';
  return new Response(req.method === 'HEAD' ? null : hit[0], {
    headers: {
      'content-type': hit[1],
      'cache-control': immutable ? 'public, max-age=31536000, immutable' : 'no-cache',
      'x-content-type-options': 'nosniff',
    },
  });
}

export default {
  ...worker,
  async fetch(req: Request, env: Parameters<typeof worker.fetch>[1], ctx: ExecutionContext): Promise<Response> {
    const url = new URL(req.url);
    if (!url.pathname.startsWith('/api/') && (req.method === 'GET' || req.method === 'HEAD')) {
      return serve(req, url.pathname) ?? new Response('Not found', { status: 404 });
    }
    return worker.fetch(req, env, ctx);
  },
};
`,
  );

  const config = JSON.parse(stripJsonComments(readFileSync(join(API, 'wrangler.jsonc'), 'utf8')));
  delete config.assets;
  delete config.$schema;
  config.main = '.web-embed/entry.ts';
  config.rules = [{ type: 'Data', globs: ['**/*.bin'], fallthrough: false }];
  writeFileSync(join(API, 'wrangler.embedded.json'), JSON.stringify(config, null, 2) + '\n');

  const bytes = used.reduce((n, f) => n + statSync(join(DIST, f)).size, 0);
  console.log(`Embedded ${used.length} of ${files.length} files (${(bytes / 1024).toFixed(0)} KB). Deploy: npx wrangler deploy -c wrangler.embedded.json`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
